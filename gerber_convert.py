def get_easyeda_header(layer_name):
    """生成完全符合 Gerber 1 的标准文件头"""
    return (
        f"G04 Layer: {layer_name}*\n"
        "G04 EasyEDA Pro v3.2.91, 2026-05-18 19:16:14*\n"
        "G04 Gerber Generator version 0.3*\n"
        "G04 Scale: 100 percent, Rotated: No, Reflected: No*\n"
        "G04 Dimensions in millimeters*\n"
        "G04 Leading zeros omitted, absolute positions, 4 integers and 5 decimals*\n"
        "G04 Generated by one-click*\n"
        "%FSLAX45Y45*%\n"
        "%MOMM*%"
    )

def get_carrier_spec(layer_name: str):
    if layer_name in CARRIER_CONFIG:
        return CARRIER_CONFIG[layer_name]
    if layer_name.startswith('InnerLayer'):
        return (16, lambda d, p: f'%ADD{d}C,1.52{p}*%')
    return None

def identify_layer(filename, gbrjob_data=None):
    base = os.path.basename(filename)
    
    # 忽略钻孔图纸与映射文件（如 *-drl_map.gbr）
    if re.search(r'(?i)[-_]drl[._-]map\.gbr$', base) or re.search(r'(?i)[-_]map\.gbr$', base):
        return (None, None)

    # 1. 优先通过 KiCad 的 .gbrjob JSON 属性精确判定图层职责
    if gbrjob_data and 'FilesAttributes' in gbrjob_data:
        for attr in gbrjob_data['FilesAttributes']:
            if attr.get('Path') == base or os.path.basename(attr.get('Path', '')) == base:
                func = attr.get('FileFunction', '')
                if 'Profile' in func: return ('Gerber_BoardOutlineLayer.GKO', 'BoardOutlineLayer')
                if func == 'Copper,L1,Top': return ('Gerber_TopLayer.GTL', 'TopLayer')
                if func.startswith('Copper,') and 'Bot' in func: return ('Gerber_BottomLayer.GBL', 'BottomLayer')
                m_inr = re.search(r'Copper,L(\d+),Inr', func)
                if m_inr:
                    layer_num = int(m_inr.group(1)) - 1
                    return (f'Gerber_InnerLayer{layer_num}.G{layer_num}', f'InnerLayer{layer_num}')
                if 'SolderMask,Top' in func or 'Soldermask,Top' in func: return ('Gerber_TopSolderMaskLayer.GTS', 'TopSolderMaskLayer')
                if 'SolderMask,Bot' in func or 'Soldermask,Bot' in func: return ('Gerber_BottomSolderMaskLayer.GBS', 'BottomSolderMaskLayer')
                if 'Legend,Top' in func: return ('Gerber_TopSilkscreenLayer.GTO', 'TopSilkscreenLayer')
                if 'Legend,Bot' in func: return ('Gerber_BottomSilkscreenLayer.GBO', 'BottomSilkscreenLayer')
                if 'SolderPaste,Top' in func or 'Paste,Top' in func: return ('Gerber_TopPasteMaskLayer.GTP', 'TopPasteMaskLayer')
                if 'SolderPaste,Bot' in func or 'Paste,Bot' in func: return ('Gerber_BottomPasteMaskLayer.GBP', 'BottomPasteMaskLayer')

    # 2. 从文件头部读取 Gerber X2 %TF.FileFunction 元数据（支持标准 %TF 与注释 G04 #@! TF 形式）
    if os.path.isfile(filename):
        try:
            with open(filename, 'r', errors='ignore') as fp:
                head = fp.read(2048)
            m_tf = re.search(r'(?:%TF\.FileFunction,|G04\s*#@!\s*TF\.FileFunction,)([^*%\r\n]+)', head)
            if m_tf:
                func = m_tf.group(1).strip()
                if 'Profile' in func: return ('Gerber_BoardOutlineLayer.GKO', 'BoardOutlineLayer')
                if re.search(r'Copper,(?:L1|1),Top', func, re.I): return ('Gerber_TopLayer.GTL', 'TopLayer')
                if re.search(r'Copper,.*Bot', func, re.I): return ('Gerber_BottomLayer.GBL', 'BottomLayer')
                m_inr = re.search(r'Copper,(?:L)?(\d+),Inr', func, re.I)
                if m_inr:
                    layer_num = int(m_inr.group(1)) - 1
                    return (f'Gerber_InnerLayer{layer_num}.G{layer_num}', f'InnerLayer{layer_num}')
                if re.search(r'SolderMask,Top', func, re.I): return ('Gerber_TopSolderMaskLayer.GTS', 'TopSolderMaskLayer')
                if re.search(r'SolderMask,Bot', func, re.I): return ('Gerber_BottomSolderMaskLayer.GBS', 'BottomSolderMaskLayer')
                if re.search(r'Legend,Top', func, re.I): return ('Gerber_TopSilkscreenLayer.GTO', 'TopSilkscreenLayer')
                if re.search(r'Legend,Bot', func, re.I): return ('Gerber_BottomSilkscreenLayer.GBO', 'BottomSilkscreenLayer')
                if re.search(r'(?:Solder)?Paste,Top', func, re.I): return ('Gerber_TopPasteMaskLayer.GTP', 'TopPasteMaskLayer')
                if re.search(r'(?:Solder)?Paste,Bot', func, re.I): return ('Gerber_BottomPasteMaskLayer.GBP', 'BottomPasteMaskLayer')
        except Exception:
            pass

    # 3. 动态匹配内层文件名命名（支持 4层、6层、8层乃至多层板如 In1_Cu, Inner2_Cu, Inr3_Cu 等）
    m_inr_name = re.search(r'(?i)(?:^|[-_])(?:In|Inner|Inr)(\d+)[._-]Cu(?:\.gbr|\.g\d+)$', base)
    if m_inr_name:
        layer_num = int(m_inr_name.group(1))
        return (f'Gerber_InnerLayer{layer_num}.G{layer_num}', f'InnerLayer{layer_num}')

    # 4. 常规规则库匹配
    for pattern, target, layer_name in LAYER_MAPPINGS:
        if re.search(pattern, base):
            return (target, layer_name)

    # 5. Protel / Altium 标准图层后缀保底映射
    protel_ext_map = {
        '.gtl': ('Gerber_TopLayer.GTL', 'TopLayer'),
        '.gbl': ('Gerber_BottomLayer.GBL', 'BottomLayer'),
        '.gts': ('Gerber_TopSolderMaskLayer.GTS', 'TopSolderMaskLayer'),
        '.gbs': ('Gerber_BottomSolderMaskLayer.GBS', 'BottomSolderMaskLayer'),
        '.gto': ('Gerber_TopSilkscreenLayer.GTO', 'TopSilkscreenLayer'),
        '.gbo': ('Gerber_BottomSilkscreenLayer.GBO', 'BottomSilkscreenLayer'),
        '.gtp': ('Gerber_TopPasteMaskLayer.GTP', 'TopPasteMaskLayer'),
        '.gbp': ('Gerber_BottomPasteMaskLayer.GBP', 'BottomPasteMaskLayer'),
        '.gko': ('Gerber_BoardOutlineLayer.GKO', 'BoardOutlineLayer'),
        '.gml': ('Gerber_BoardOutlineLayer.GKO', 'BoardOutlineLayer'),
        '.gm1': ('Gerber_BoardOutlineLayer.GKO', 'BoardOutlineLayer'),
        '.gm2': ('Gerber_BoardOutlineLayer.GKO', 'BoardOutlineLayer'),
    }
    ext = os.path.splitext(base)[1].lower()
    if ext in protel_ext_map:
        return protel_ext_map[ext]

    return (None, None)

def process_macro(name, full_macro_text):
    if name == 'RoundRect':
        return EASYEDA_ROUNDRECT_MACRO
    else:
        parts = full_macro_text.replace('\n', '').replace('\r', '')
        return re.sub(r'0\s+[^\\*]+\*', '', parts)

def inject_lceda_carrier(content: str, layer_name: str) -> str:
    """
    基于 GhostPCB 逆向算法，动态计算并注入立创EDA防伪溯源哈希载体光圈：
    1. 在指定的保留 D 码（如 D15 / D16 / D11）预留载体插槽，将原文件中 >= 载体 D 码的所有光圈定义及引用自动顺延 +1；
    2. 计算排除载体光圈后的完整文件 MD5，取十六进制哈希后两位转十进制并取模 100，得到 2 位校验数字对（pair）；
    3. 将 pair 嵌入载体光圈第一参数的小数点后第 3、4 位（如 0.18{pair}、0.91{pair}X2.69999）；
    4. 将载体定义精准插入文件头 %ADD 块中，确保在图元绘制中从未被调用（引用次数为 0），完美通过立创EDA哈希校验。
    """
    carrier_spec = get_carrier_spec(layer_name)
    if not carrier_spec:
        return content

    carrier_dcode, builder = carrier_spec
    eol = '\n'
    has_trailing = True
    lines = content.splitlines()

    tool_select_re = re.compile(r'^(G54D|D)(\d{2,})\*$')
    add_re = re.compile(r'^%ADD(\d+)(.*)\*%$')

    # 1. 顺延 >= carrier_dcode 的现有光圈定义及引用
    shifted_lines = []
    for line in lines:
        sline = line.strip()
        m_add = add_re.match(sline)
        if m_add:
            d = int(m_add.group(1))
            rest = m_add.group(2)
            if d >= carrier_dcode:
                d += 1
            shifted_lines.append(f'%ADD{d}{rest}*%')
            continue

        m_tool = tool_select_re.match(sline)
        if m_tool:
            prefix = m_tool.group(1)
            d = int(m_tool.group(2))
            if d >= carrier_dcode:
                d += 1
            shifted_lines.append(f'{prefix}{d}*')
            continue

        shifted_lines.append(line)

    # 2. 组装未插入载体光圈时的完整文本并计算 MD5 校验对
    shifted_content = eol.join(shifted_lines)
    if has_trailing:
        shifted_content += eol

    digest = hashlib.md5(shifted_content.encode('utf-8')).hexdigest()
    last_byte = int(digest[-2:], 16)
    pair = f'{last_byte % 100:02d}'

    # 3. 构建带动态 MD5 校验对的载体光圈语句
    carrier_line = builder(carrier_dcode, pair)

    # 4. 精准寻找插入位置（紧随 %ADD 块中）
    next_add_prefix = f'%ADD{carrier_dcode + 1}'
    insert_idx = -1
    for i, line in enumerate(shifted_lines):
        if line.strip().startswith(next_add_prefix):
            insert_idx = i
            break

    if insert_idx == -1:
        last_add_idx = -1
        for i, line in enumerate(shifted_lines):
            if add_re.match(line.strip()):
                last_add_idx = i
        if last_add_idx != -1:
            insert_idx = last_add_idx + 1

    if insert_idx == -1:
        for i, line in enumerate(shifted_lines):
            if line.strip().startswith('%MOMM'):
                insert_idx = i + 1
                break

    if insert_idx == -1:
        insert_idx = len(shifted_lines)

    result_lines = list(shifted_lines)
    result_lines.insert(insert_idx, carrier_line)

    result_content = eol.join(result_lines)
    if has_trailing:
        result_content += eol

    return result_content

def convert_gerber(content, layer_name):
    is_46 = '%FSLAX46Y46*%' in content
    lines = content.splitlines()
    clean_lines = []
    
    in_macro = False
    macro_name = ''
    macro_buffer = []

    for line in lines:
        sline = line.strip()
        if not sline: continue
        
        # 彻底去除 KiCad X2 属性标签与注释指令
        if sline.startswith(('G04 #@!', '%TF.', '%TA.', '%TO.', '%TD')):
            continue
        # 去除 KiCad 初始格式定义与注释，后续统一替换为 Gerber 1 标头
        if sline.startswith(('%FSLA', '%MOMM', 'G04 Gerber Fmt', 'G04 Created by KiCad', 'G04 APERTURE')):
            continue
            
        # 捕获并规范化光圈宏
        if sline.startswith('%AM'):
            in_macro = True
            m = re.match(r'%AM([^*]+)\*', sline)
            macro_name = m.group(1) if m else ''
            macro_buffer = [sline]
            if sline.endswith('%'):
                in_macro = False
                res = process_macro(macro_name, '\n'.join(macro_buffer))
                if res: clean_lines.append(res)
            continue
        elif in_macro:
            macro_buffer.append(sline)
            if sline.endswith('%'):
                in_macro = False
                res = process_macro(macro_name, '\n'.join(macro_buffer))
                if res: clean_lines.append(res)
            continue

        # 将独立换刀指令 Dxx* 转换为 Gerber 1 格式的 G54Dxx*
        m_tool = re.match(r'^D(\d{2,})\*$', sline)
        if m_tool:
            clean_lines.append(f'G54D{m_tool.group(1)}*')
            continue

        clean_lines.append(sline)

    text = '\n'.join(clean_lines)

    # 将 10 参数 RoundRect 调用转换为 5 参数
    def repl_add_rr(m):
        dcode = m.group(1)
        params = [float(p) for p in m.group(2).split('X')]
        if len(params) == 10:
            radius, x1, y1, x2, y2, x3, y3, x4, y4, rot = params
            return f'%ADD{dcode}RoundRect,{radius*2.0:g}X{x1:g}X{y1:g}X{x2:g}X{y2:g}*%'
        return m.group(0)

    text = re.sub(r'%ADD(\d+)RoundRect,([\d\.\-eEX]+)\*%', repl_add_rr, text)

    # 4.6 降阶到 4.5 整数坐标
    if is_46:
        coord_re = re.compile(r'([XYIJ])([+-]?\d+)')
        res_lines = []
        for l in text.splitlines():
            if l.startswith(('%', 'G04', 'M02', 'M00')):
                res_lines.append(l)
            else:
                def repl_coord(m):
                    return f"{m.group(1)}{int(round(int(m.group(2)) / 10.0))}"
                res_lines.append(coord_re.sub(repl_coord, l))
        text = '\n'.join(res_lines)

    # 拼装完整的 Gerber 1 文件头
    header = get_easyeda_header(layer_name)
    full_content = f"{header}\n{text}\n"

    # 动态计算 MD5 并注入立创EDA防伪哈希载体光圈
    return inject_lceda_carrier(full_content, layer_name)

def count_drill_features(coords):
    """统计实际钻孔与槽孔数量（避免将多行铣削指令重复计数）"""
    count = 0
    for line in coords:
        if line.startswith(('X', 'Y', 'G85', 'G00')):
            count += 1
    return count

def extract_drill_points_for_drawing(coords):
    """
    从刀具坐标行中提取用于钻孔字符图层(GDD)的绘制中心点
    支持普通钻孔(X...Y...)、模态坐标、G85槽孔、以及铣槽(G00..M15..G01..M16)
    """
    points = []
    x_re = re.compile(r'X([+-]?[\d\.]+)')
    y_re = re.compile(r'Y([+-]?[\d\.]+)')
    
    curr_x = 0.0
    curr_y = 0.0
    
    i = 0
    while i < len(coords):
        line = coords[i]
        if line.startswith('G00'):
            # 铣槽起始点 (G00)
            mx = x_re.search(line)
            my = y_re.search(line)
            if mx: curr_x = float(mx.group(1))
            if my: curr_y = float(my.group(1))
            x1, y1 = curr_x, curr_y
            
            # 寻找配对的终点 (G01)
            j = i + 1
            x2, y2 = x1, y1
            while j < len(coords) and not coords[j].startswith(('G00', 'T', 'M30')):
                if coords[j].startswith('G01'):
                    mx2 = x_re.search(coords[j])
                    my2 = y_re.search(coords[j])
                    if mx2: curr_x = float(mx2.group(1))
                    if my2: curr_y = float(my2.group(1))
                    x2, y2 = curr_x, curr_y
                    break
                j += 1
            # 取槽孔中心点绘制符号
            points.append(((x1 + x2) / 2.0, (y1 + y2) / 2.0))
            i = j + 1
            continue
        elif line.startswith('G85'):
            # G85 槽孔，例如 G85X1Y1X2Y2 或 G85X2Y2
            all_x = [float(x) for x in x_re.findall(line)]
            all_y = [float(y) for y in y_re.findall(line)]
            if len(all_x) >= 2 and len(all_y) >= 2:
                points.append(((all_x[0] + all_x[1]) / 2.0, (all_y[0] + all_y[1]) / 2.0))
                curr_x, curr_y = all_x[1], all_y[1]
            elif len(all_x) >= 1 and len(all_y) >= 1:
                points.append(((curr_x + all_x[0]) / 2.0, (curr_y + all_y[0]) / 2.0))
                curr_x, curr_y = all_x[0], all_y[0]
        elif line.startswith(('X', 'Y')):
            mx = x_re.search(line)
            my = y_re.search(line)
            if mx: curr_x = float(mx.group(1))
            if my: curr_y = float(my.group(1))
            points.append((curr_x, curr_y))
        i += 1
    return points

def parse_drill_content(content):
    """解析钻孔文件中的刀具信息与坐标/槽孔列表"""
    lines = content.splitlines()
    tools = {}
    current_func = ''
    
    for line in lines:
        line = line.strip()
        if line.startswith('; #@! TA.AperFunction'):
            current_func = line.split(',')[-1].strip()
        m = re.match(r'^T(\d+)C([\d\.]+)', line)
        if m:
            t_num = int(m.group(1))
            size = float(m.group(2))
            tools[t_num] = {'size': size, 'func': current_func}
            current_func = ''
        elif line == '%':
            break

    in_body = False
    tool_coords = {}
    current_tool = None

    for line in lines:
        line = line.strip()
        if not in_body:
            if line == '%':
                in_body = True
            continue
        
        if not line or line.startswith(';') or line == 'M30':
            continue
        
        m = re.match(r'^T(\d+)$', line)
        if m:
            current_tool = int(m.group(1))
            if current_tool not in tool_coords:
                tool_coords[current_tool] = []
            continue
        
        if current_tool is not None:
            # 完整捕获普通圆孔、槽孔铣削指令 (G00/G01/M15/M16/G05) 及 G85 槽孔指令
            if (line.startswith(('X', 'Y', 'G', 'M')) and 
                not line.startswith(('T', 'M30', 'M48'))):
                tool_coords[current_tool].append(line)

    return tools, tool_coords

def format_drill_file(layer_name, is_plated, tool_data_list):
    """
    按照 Gerber 1 格式生成标准 Excellon 钻孔文件
    tool_data_list: [(diam, [coords])]
    """
    lines = [
        f";TYPE={'PLATED' if is_plated else 'NON_PLATED'}",
        f";Layer: {layer_name}",
        ";EasyEDA Pro v3.2.91, 2026-05-18 19:16:14",
        ";Gerber Generator version 0.3",
        "M48",
        "METRIC,LZ,0000.00000"
    ]
    
    # 头部刀具声明
    for idx, (diam, _) in enumerate(tool_data_list, 1):
        lines.append(f";Hole size {idx} = {diam:.5f} METRIC")
        lines.append(f"T{idx:02d}C{diam:.5f}")
        
    lines.extend(["%", "G05", "G90"])
    
    # 坐标体
    for idx, (_, coords) in enumerate(tool_data_list, 1):
        if coords:
            lines.append(f"T{idx:02d}")
            lines.extend(coords)
            
    lines.append("M30")
    return '\n'.join(lines) + '\n'

