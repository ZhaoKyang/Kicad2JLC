def convert_directory(input_dir, output_dir):
    os.makedirs(output_dir, exist_ok=True)
    
    temp_dir_to_clean = None
    if os.path.isfile(input_dir) and input_dir.lower().endswith('.zip'):
        import tempfile
        temp_dir_to_clean = tempfile.mkdtemp(prefix='gerber_zip_')
        with zipfile.ZipFile(input_dir, 'r') as zf:
            zf.extractall(temp_dir_to_clean)
        # 若 ZIP 压缩包内部嵌套了单个子文件夹（如 Gerbers/），自动下钻到该子目录
        sub_items = [os.path.join(temp_dir_to_clean, x) for x in os.listdir(temp_dir_to_clean) if not x.startswith('__')]
        if len(sub_items) == 1 and os.path.isdir(sub_items[0]):
            input_dir = sub_items[0]
        else:
            input_dir = temp_dir_to_clean

    gbrjob_data = None
    for f in os.listdir(input_dir):
        if f.endswith('.gbrjob'):
            try:
                with open(os.path.join(input_dir, f), 'r', encoding='utf-8') as jf:
                    gbrjob_data = json.load(jf)
            except Exception: pass

    converted_files = []
    all_drill_tools_for_gdd = []

    # 1. 转换标准图形图层并注入哈希载体光圈
    for fname in os.listdir(input_dir):
        fpath = os.path.join(input_dir, fname)
        if not os.path.isfile(fpath) or fname.endswith(('.zip', '.gbrjob', '.drl', '.txt')):
            continue

        target_name, layer_name = identify_layer(fpath, gbrjob_data)
        if not target_name:
            continue

        out_path = os.path.join(output_dir, target_name)
        with open(fpath, 'r', errors='ignore') as fp:
            raw_content = fp.read()

        converted = convert_gerber(raw_content, layer_name)
        with open(out_path, 'w', encoding='utf-8', newline='\n') as fp:
            fp.write(converted)

        carrier_spec = get_carrier_spec(layer_name)
        carrier_d = carrier_spec[0] if carrier_spec else None
        print(f"[图层转换] {fname:25s} -> {target_name} (动态计算并注入 MD5 哈希载体: D{carrier_d})")
        converted_files.append(out_path)

    # 2. 转换并严格拆分钻孔文件 (PTH_Through, PTH_Through_Via, NPTH_Through)
    pth_file = None
    npth_file = None
    for fname in os.listdir(input_dir):
        if fname.lower().endswith(('.drl', '.txt')):
            if 'npth' in fname.lower():
                npth_file = os.path.join(input_dir, fname)
            elif 'pth' in fname.lower():
                pth_file = os.path.join(input_dir, fname)

    # 处理金属化沉铜钻孔文件 (PTH)
    if pth_file and os.path.isfile(pth_file):
        with open(pth_file, 'r', errors='ignore') as fp:
            raw_pth = fp.read()
        tools, tool_coords = parse_drill_content(raw_pth)

        via_tools = []
        all_pth_tools = []

        for t_num in sorted(tools.keys()):
            diam = tools[t_num]['size']
            func = tools[t_num]['func']
            coords = tool_coords.get(t_num, [])
            if not coords:
                continue

            all_pth_tools.append((diam, coords))
            all_drill_tools_for_gdd.append((diam, coords))

            # 判定是否为过孔：优先依据 X2 元数据声明，若无元数据则孔径 <= 0.4mm 视作过孔
            is_via = False
            if 'viadrill' in func.lower():
                is_via = True
            elif 'componentdrill' in func.lower():
                is_via = False
            elif diam <= 0.4:
                is_via = True

            if is_via:
                via_tools.append((diam, coords))

        # 生成 1: Drill_PTH_Through.DRL (包含全部金属化孔)
        out_pth = os.path.join(output_dir, 'Drill_PTH_Through.DRL')
        with open(out_pth, 'w', encoding='utf-8', newline='\n') as fp:
            fp.write(format_drill_file('PTH_Through', True, all_pth_tools))
        total_pth_count = sum(count_drill_features(c) for _, c in all_pth_tools)
        print(f"[钻孔转换] {os.path.basename(pth_file):25s} -> Drill_PTH_Through.DRL (全量金属化孔/槽孔: {total_pth_count} 个)")
        converted_files.append(out_pth)

        # 生成 2: Drill_PTH_Through_Via.DRL (独立过孔文件，严格对齐 Gerber 1)
        if via_tools:
            out_via = os.path.join(output_dir, 'Drill_PTH_Through_Via.DRL')
            with open(out_via, 'w', encoding='utf-8', newline='\n') as fp:
                fp.write(format_drill_file('PTH_Through_Via', True, via_tools))
            total_via_count = sum(count_drill_features(c) for _, c in via_tools)
            print(f"[钻孔拆分] 生成独立过孔文件         -> Drill_PTH_Through_Via.DRL (独立过孔: {total_via_count} 个)")
            converted_files.append(out_via)

    # 处理非金属化钻孔文件 (NPTH)
    if npth_file and os.path.isfile(npth_file):
        with open(npth_file, 'r', errors='ignore') as fp:
            raw_npth = fp.read()
        npth_tools, npth_coords = parse_drill_content(raw_npth)
        npth_tool_list = []
        for t_num in sorted(npth_tools.keys()):
            diam = npth_tools[t_num]['size']
            coords = npth_coords.get(t_num, [])
            if coords:
                npth_tool_list.append((diam, coords))
                all_drill_tools_for_gdd.append((diam, coords))

        out_npth = os.path.join(output_dir, 'Drill_NPTH_Through.DRL')
        with open(out_npth, 'w', encoding='utf-8', newline='\n') as fp:
            fp.write(format_drill_file('NPTH_Through', False, npth_tool_list))
        total_npth_count = sum(count_drill_features(c) for _, c in npth_tool_list)
        print(f"[钻孔转换] {os.path.basename(npth_file):25s} -> Drill_NPTH_Through.DRL (非金属化孔/槽孔: {total_npth_count} 个)")
        converted_files.append(out_npth)

    # 3. 自动生成钻孔符号图层 (Gerber_DrillDrawingLayer.GDD) 并注入 D15 载体
    if all_drill_tools_for_gdd:
        gdd_path = os.path.join(output_dir, 'Gerber_DrillDrawingLayer.GDD')
        with open(gdd_path, 'w', encoding='utf-8', newline='\n') as fp:
            fp.write(generate_drill_drawing(all_drill_tools_for_gdd))
        print(f"[生成图层] 自动合成钻孔字符图层    -> Gerber_DrillDrawingLayer.GDD (注入哈希载体光圈: D15)")
        converted_files.append(gdd_path)

    # 4. 生成立创下单说明文档
    readme_path = os.path.join(output_dir, 'PCB下单必读.txt')
    with open(readme_path, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write("如何进行PCB下单\n\n请查看：\nhttps://prodocs.lceda.cn/cn/pcb/order-order-pcb/index.html\n")
    converted_files.append(readme_path)

    # 5. 打包为可以在立创EDA一键导入的 ZIP 压缩包
    zip_path = os.path.join(output_dir, "Gerber_Converted_for_EasyEDA.zip")
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        for f in converted_files:
            zf.write(f, os.path.basename(f))
    print(f"\n[打包成功] 生成生产级压缩包: {zip_path}")
    if temp_dir_to_clean and os.path.exists(temp_dir_to_clean):
        import shutil
        shutil.rmtree(temp_dir_to_clean, ignore_errors=True)

    validate_archive(zip_path)
    return zip_path

def validate_archive(zip_path):
    """
    自检验证压缩包内的所有 Gerber 图层是否具备合法的立创EDA防伪哈希载体
    """
    print("\n========== 立创EDA防伪哈希载体自检报告 ==========")
    all_passed = True
    with zipfile.ZipFile(zip_path, 'r') as zf:
        for name in sorted(zf.namelist()):
            if not (name.endswith(('.GTL', '.GBL', '.GKO', '.GTS', '.GBS', '.GTO', '.GBO', '.GTP', '.GBP', '.GDD')) or name.startswith('Gerber_')):
                continue
            content = zf.read(name).decode('utf-8', errors='ignore')
            lines = content.splitlines()
            eol = '\r\n' if '\r\n' in content else '\n'
            has_trailing = content.endswith('\n')

            add_lines = []
            for idx, line in enumerate(lines):
                m = re.match(r'^%ADD(\d+)([^,]+),(.*)\*%$', line.strip())
                if m:
                    add_lines.append((int(m.group(1)), line, idx, m.group(2), m.group(3)))

            used = set()
            for l in lines:
                for m in re.finditer(r'(?:G54)?D(\d{2,4})\*', l):
                    used.add(int(m.group(1)))

            unused = [x for x in add_lines if x[0] not in used]
            found = False
            for uid, uline, uidx, shape, params in unused:
                m_param = re.match(r'^([+-]?\d+(?:\.\d+)?)(.*)$', params)
                if not m_param: continue
                first_param = m_param.group(1)
                dec_part = first_param.split('.')[1] if '.' in first_param else ''
                embedded_pair = dec_part[2:4] if len(dec_part) >= 4 else (dec_part[2] + '0' if len(dec_part) == 3 else None)
                if not embedded_pair: continue

                rem_lines = [l for i, l in enumerate(lines) if i != uidx]
                rem_content = eol.join(rem_lines)
                if has_trailing: rem_content += eol

                digest = hashlib.md5(rem_content.encode('utf-8')).hexdigest()
                pair = f"{int(digest[-2:], 16) % 100:02d}"

                if embedded_pair == pair:
                    print(f"  [文件] {name:32s} | 载体: D{uid:02d} ({shape},{first_param}) | 校验: ✅ 匹配通过 (嵌入值={embedded_pair}, 计算值={pair})")
                    found = True
                    break

            if not found:
                print(f"  [文件] {name:32s} | 校验: ❌ 未找到匹配的哈希载体光圈")
                all_passed = False

    if all_passed:
        print(">> 隐藏哈希值检验: ✅ 100% 全部图层载体校验通过！可被立创EDA官方/在线版无阻打开！\n")
    else:
        print(">> 隐藏哈希值检验: ⚠ 部分图层未通过\n")
    return all_passed

